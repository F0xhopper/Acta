/** Generates src/content/site.ts for a site repo from brand.json and facts.json. The copywriter rewrites the copy fields. */
import type { Brand, Facts } from './contracts.js';
import { slugify } from '../util/slug.js';

/** public/brand/logo.png -> /brand/logo.png. Tolerates an absolute path by keeping everything from /brand/ on. */
const publicPath = (p: string | null | undefined) => {
  if (!p) return null;
  const i = p.indexOf('/brand/');
  if (i >= 0) return p.slice(i);
  return '/' + p.replace(/^\/?public\//, '').replace(/^\//, '');
};

export function siteContentSource(brand: Brand, facts: Facts): string {
  const b = facts.business;
  const label = b.category_label.toLowerCase();
  const services = facts.services.slice(0, 8).map((s) => ({
    slug: slugify(s.name), name: s.name,
    summary: `${s.name} in ${b.area} and across ${b.city}.`,
    body: `TODO copywriter: describe ${s.name} for ${b.name}. Use only facts from acta/facts.json.`,
    ...(s.evidence ? { evidence: s.evidence } : {}),
  }));
  if (!services.length) services.push({ slug: 'our-services', name: 'Our services', summary: `What ${b.name} offers in ${b.area}.`, body: `TODO copywriter: describe what ${b.name} offers.` });
  const asUrl = (v?: string) => (v ? (/^https?:\/\//i.test(v) ? v : `https://${v.replace(/^@/, '')}`) : undefined);
  const social = Object.fromEntries(Object.entries(brand.social).map(([k, v]) => [k, asUrl(v as string | undefined)]).filter(([, v]) => v));
  const email = b.email && /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(b.email) ? b.email : null;
  const areas = facts.areas.slice(0, 8).map((a) => ({ slug: slugify(a), name: a, body: `TODO copywriter: ${b.name} serving ${a}.` }));
  const site = {
    business: {
      name: b.name, phone_e164: b.phone_e164, phone_display: b.phone_display, whatsapp: b.whatsapp, email, address: b.address, postcode: b.postcode,
      area: b.area, city: b.city, maps_url: b.maps_url, place_id: b.place_id ?? null, lat: b.lat ?? null, lng: b.lng ?? null, hours: b.hours, rating: b.rating, review_count: b.review_count,
    },
    copy: {
      tagline: `${label.charAt(0).toUpperCase() + label.slice(1)} in ${b.area}`,
      hero_heading: `TODO copywriter: hero heading for ${b.name}`,
      hero_sub: `TODO copywriter: one line on what ${b.name} does and for whom.`,
      about_heading: `About ${b.name}`,
      about_body: b.description ?? `TODO copywriter: about ${b.name}.`,
      cta_label: b.phone_display ? `Call ${b.phone_display}` : 'Get in touch',
      cta_sub: 'TODO copywriter: one line under the call to action.',
    },
    services, areas,
    reviews: facts.reviews.filter((r) => (r.rating ?? 0) >= 4 && r.text).slice(0, 6).map((r) => ({ rating: r.rating ?? 5, text: r.text, author: r.author ?? 'Google review', when: r.when ?? '' })),
    claims: facts.claims.map((c) => c.claim),
    social,
    logo: brand.logo.path ? { path: publicPath(brand.logo.path)!, alt: `${b.name} logo` } : null,
    photos: brand.photos.map((p) => ({ path: publicPath(p.path)!, alt: p.alt ?? `${b.name}, ${label} in ${b.area}` })),
    meta: {
      title: `${b.name} | ${b.category_label} in ${b.area}`.slice(0, 70),
      description: (b.description ?? `${b.name}, ${label} in ${b.area}, ${b.city}. ${b.phone_display ? `Call ${b.phone_display}.` : ''}`).slice(0, 155),
    },
  };
  return `// Generated by Acta from acta/facts.json and acta/brand.json. Every fact on the site comes from here.
// The copywriter replaces every TODO. Facts (phone, address, hours, claims) must not be changed by hand.
import type { Site } from '@/kit/site-schema';

const site: Site = ${JSON.stringify(site, null, 2)};

export default site;
`;
}
